"""Real per-request PDF, editable Word, and structured Excel exports for AI-5.

No file is saved to a public static directory; authenticated API responses
stream the generated bytes. Export failure cannot modify the saved turn.
"""
import html
import io
import re
from datetime import datetime,timezone
from pathlib import Path

CITE=re.compile(r"\[\[([A-Z0-9:_-]{3,80})\]\]")
HEAD=re.compile(r"^(#{1,4})\s+(.+)$")
LIST=re.compile(r"^\s*[-*]\s+(.+)$")


def _plain(text):
    text=CITE.sub(lambda m:"["+m.group(1)+"]",str(text or ""))
    return re.sub(r"(?<!\\)[*_\x60]","",text)


def _outline(turn,edited_text=""):
    a=turn["answer"]
    body=edited_text or a.get("draft") or a.get("body") or ""
    return body[:21000],a.get("table") or {},a.get("open_questions") or []


def _sources(turn):
    ids=set()
    for text in (turn.get("answer",{}).get("body",""),
                 turn.get("answer",{}).get("draft","")):
        ids.update(CITE.findall(text))
    for s in turn.get("sources",[]):
        if s.get("id") in ids or s.get("type","").startswith("ATTACHMENT_"):
            yield s


def _font():
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    for path in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    ):
        if Path(path).is_file():
            try:
                if "AI5Unicode" not in pdfmetrics.getRegisteredFontNames():
                    pdfmetrics.registerFont(TTFont("AI5Unicode",path))
                return "AI5Unicode"
            except Exception:
                pass
    return "Helvetica"


def create_pdf(turn,edited=""):
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate,Paragraph,Spacer,Table,TableStyle,KeepTogether

    out=io.BytesIO()
    doc=SimpleDocTemplate(out,pagesize=A4,leftMargin=19*mm,rightMargin=19*mm,
                           topMargin=19*mm,bottomMargin=19*mm,title="AI-5 Research Export")
    font=_font()
    normal=ParagraphStyle("AI5Body",fontName=font,fontSize=9.4,leading=14,spaceAfter=7,
                          wordWrap="CJK")
    heading=ParagraphStyle("AI5Heading",parent=normal,fontSize=13,leading=17,
                           spaceBefore=11,spaceAfter=8,textColor=colors.HexColor("#173950"))
    small=ParagraphStyle("AI5Source",parent=normal,fontSize=8,leading=12,
                         textColor=colors.HexColor("#4B5563"))
    story=[Paragraph(html.escape(turn["answer"].get("title") or "AI-5 Research"),
                     heading),Spacer(1,5)]
    body,table,questions=_outline(turn,edited)
    for line in body.split("\n"):
        x=line.strip()
        if not x:
            story.append(Spacer(1,4));continue
        m=HEAD.match(x)
        if m:story.append(Paragraph(html.escape(_plain(m.group(2))),heading))
        else:
            li=LIST.match(x)
            story.append(Paragraph(html.escape(("• "+_plain(li.group(1))) if li else _plain(x)),normal))
    cols=table.get("columns") or []
    rows=table.get("rows") or []
    if cols:
        story.append(Paragraph(html.escape(table.get("title") or "Structured comparison"),heading))
        # Long/wide tables are presented as individual rows to preserve
        # legibility on portrait A4 rather than silently dropping columns.
        if len(cols)>5:
            for i,row in enumerate(rows[:100],1):
                story.append(Paragraph(f"Row {i}",heading))
                for j,name in enumerate(cols):
                    value=str(row[j]) if j<len(row) else ""
                    story.append(Paragraph(html.escape(str(name)+": "+value[:900]),normal))
        else:
            cells=[[Paragraph(html.escape(str(x)),small) for x in cols]]
            for row in rows[:100]:
                cells.append([Paragraph(html.escape(str(row[i])[:800] if i<len(row) else ""),small)
                              for i in range(len(cols))])
            width=(A4[0]-38*mm)/len(cols)
            sheet=Table(cells,colWidths=[width]*len(cols),repeatRows=1,hAlign="LEFT")
            sheet.setStyle(TableStyle([
                ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#E7EDF1")),
                ("GRID",(0,0),(-1,-1),.25,colors.HexColor("#CFD8DF")),
                ("VALIGN",(0,0),(-1,-1),"TOP"),("LEFTPADDING",(0,0),(-1,-1),5),
                ("RIGHTPADDING",(0,0),(-1,-1),5),("BOTTOMPADDING",(0,0),(-1,-1),6)
            ]))
            story.append(sheet)
    if questions:
        story.append(Paragraph("Open questions / caveats",heading))
        for q in questions:story.append(Paragraph(html.escape(_plain(q)),normal))
    story.append(Paragraph("Research sources and provenance",heading))
    selected=list(_sources(turn))
    if not selected:story.append(Paragraph("No source citations attached.",small))
    for s in selected[:50]:
        desc=(str(s.get("id"))+" — "+str(s.get("title") or "")+
              " | "+str(s.get("read_status") or "")+
              " | "+str(s.get("published_at") or "date unknown")+
              (" | "+str(s.get("resolved_url") or s.get("url")) if s.get("url") else ""))
        story.append(Paragraph(html.escape(desc[:700]),small))
    story.append(Paragraph("Generated for review. No official decision or communication was executed.",small))
    doc.build(story)
    return out.getvalue()


def create_docx(turn,edited=""):
    from docx import Document
    from docx.shared import Inches,Pt,RGBColor
    doc=Document()
    sec=doc.sections[0]
    sec.top_margin=Inches(.8);sec.bottom_margin=Inches(.8)
    sec.left_margin=Inches(.85);sec.right_margin=Inches(.85)
    doc.add_heading(turn["answer"].get("title") or "AI-5 Research",0)
    body,table,questions=_outline(turn,edited)
    for line in body.split("\n"):
        s=line.strip()
        if not s:
            doc.add_paragraph("");continue
        if (m:=HEAD.match(s)):
            doc.add_heading(_plain(m.group(2)),level=min(3,len(m.group(1))))
        elif (m:=LIST.match(s)):
            doc.add_paragraph(_plain(m.group(1)),style="List Bullet")
        else:doc.add_paragraph(_plain(s))
    columns=table.get("columns") or []
    if columns:
        doc.add_heading(table.get("title") or "Structured comparison",level=2)
        grid=doc.add_table(rows=1,cols=len(columns))
        grid.style="Table Grid"
        for i,c in enumerate(columns):grid.rows[0].cells[i].text=str(c)
        for row in (table.get("rows") or [])[:150]:
            cells=grid.add_row().cells
            for i in range(len(columns)):cells[i].text=str(row[i])[:1600] if i<len(row) else ""
    if questions:
        doc.add_heading("Open questions / caveats",level=2)
        for q in questions:doc.add_paragraph(_plain(q),style="List Bullet")
    doc.add_heading("Research sources and provenance",level=2)
    sources=list(_sources(turn))
    if not sources:doc.add_paragraph("No source citations attached.")
    for s in sources[:60]:
        meta=(f'{s.get("id")} — {s.get("title") or "Source"}; '
              f'{s.get("read_status") or "unknown"}; '
              f'{s.get("published_at") or "date unknown"}')
        doc.add_paragraph(meta)
        if s.get("url"):doc.add_paragraph(str(s.get("resolved_url") or s.get("url")))
    doc.add_paragraph("For authorised review only; no external communication sent.")
    bio=io.BytesIO();doc.save(bio)
    return bio.getvalue()


def _literal(value):
    text=str(value or "")[:30000]
    # Prevent spreadsheet formula execution when user/model text starts with
    # common formula prefixes, including whitespace-prefixed formulas.
    return "'"+text if text.lstrip().startswith(("=","+","-","@")) else text


def create_xlsx(turn,edited=""):
    from openpyxl import Workbook
    from openpyxl.styles import PatternFill,Font,Alignment
    from openpyxl.utils import get_column_letter
    wb=Workbook()
    main=wb.active;main.title="Analysis"
    body,table,questions=_outline(turn,edited)
    columns=table.get("columns") or []
    rows=table.get("rows") or []
    if columns:
        main.append([_literal(x) for x in columns])
        for row in rows[:250]:
            main.append([_literal(row[i]) if i<len(row) else "" for i in range(len(columns))])
    else:
        main.append(["Section","Content","Status"])
        for line in body.splitlines():
            if line.strip():
                label="Heading" if HEAD.match(line) else "Finding / draft"
                main.append([label,_literal(_plain(line)), "Requires review"])
        if main.max_row==1:main.append(["Finding","No generated content","No evidence"])
    main.freeze_panes="A2"
    main.auto_filter.ref=main.dimensions
    main.sheet_view.showGridLines=False
    for cell in main[1]:
        cell.font=Font(bold=True,color="FFFFFF")
        cell.fill=PatternFill("solid",fgColor="173950")
    for col in main.columns:
        letter=get_column_letter(col[0].column)
        main.column_dimensions[letter].width=min(65,max(17,max(len(str(c.value or "")) for c in col[:70])//2+5))
        for c in col:c.alignment=Alignment(vertical="top",wrap_text=True)
    sources=wb.create_sheet("Sources")
    sources.append(["Citation ID","Source title / file section","Type","Read status","Provenance",
                    "Publication date","Direct URL"])
    for s in list(_sources(turn))[:200]:
        sources.append([_literal(s.get(k)) for k in
                       ("id","title","type","read_status","basis","published_at","url")])
    sources.freeze_panes="A2";sources.auto_filter.ref=sources.dimensions
    for cell in sources[1]:
        cell.font=Font(bold=True,color="FFFFFF")
        cell.fill=PatternFill("solid",fgColor="173950")
    for i,w in enumerate([25,58,25,20,34,20,62],1):
        sources.column_dimensions[get_column_letter(i)].width=w
    notes=wb.create_sheet("Context and caveats")
    notes.append(["Field","Value"])
    for k,v in [("Conversation mode",turn.get("mode")),("Source selection",turn.get("source_mode")),
                ("Original question",turn.get("question")),
                ("Generated at",datetime.now(timezone.utc).isoformat()),
                ("Editable draft",_plain(body[:18000])),
                ("Review policy","For review; no approval/sending/assignment was performed")]:
        notes.append([_literal(k),_literal(v)])
    for q in questions[:20]:notes.append(["Open question",_literal(q)])
    notes.column_dimensions["A"].width=27;notes.column_dimensions["B"].width=100
    for c in notes["B"]:c.alignment=Alignment(wrap_text=True,vertical="top")
    out=io.BytesIO();wb.save(out)
    return out.getvalue()


MIME={"pdf":"application/pdf",
      "docx":"application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "xlsx":"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"}


def create(turn,file_type,edited_text=""):
    if file_type not in MIME:raise ValueError("Unsupported export format")
    if not isinstance(edited_text,str) or len(edited_text)>22000:
        raise ValueError("Edited document text is too long")
    data=({"pdf":create_pdf,"docx":create_docx,"xlsx":create_xlsx}[file_type]
          (turn,edited_text))
    if not data or len(data)<100:raise ValueError("Empty or invalid generated file")
    return data,MIME[file_type],f"SmartRadar_AI5_{turn['turn_id'][:10]}.{file_type}"
