import { test, expect } from '@playwright/test';
import config from '../playwright.config.js';

const email='admin@bawaslu.local';
const password=config.webServer?.[0]?.env?.BAWASLU_BOOTSTRAP_ADMIN_PASSWORD;
test('current inline campaign editor preserves descriptions without paid provider calls',async({page})=>{
 const paid=[];page.on('request',req=>{if(/socialcrawl\.dev|api\.openai\.com/.test(req.url()))paid.push(req.url())});
 await page.goto('/login');
 await page.getByLabel(/email/i).fill(email);
 await page.getByLabel(/^password$/i).fill(password);
 await page.getByRole('button',{name:/log in|masuk/i}).click();
 await page.waitForURL(url=>!url.pathname.startsWith('/login'));
 await page.goto('/social-listening');
 await page.getByRole('button',{name:/create campaign/i}).click();
 const editor=page.getByRole('form',{name:'Campaign editor'});
 const name='QA Description '+Date.now();
 await editor.getByLabel(/campaign name/i).fill(name);
 const kw=editor.getByRole('textbox',{name:'Main keywords'});
 await kw.fill('pemilu');await kw.press('Enter');
 await editor.getByRole('button',{name:'Save Draft'}).click();
 const card=page.getByRole('article').filter({hasText:name});
 await expect(card).toBeVisible();
 await card.getByRole('button',{name:'Edit'}).click();
 const description='Monitor Indonesian election oversight using saved original evidence.';
 await editor.getByLabel('Description').fill(description);
 await editor.getByRole('button',{name:'Save Draft'}).click();
 await page.reload();
 const restored=page.getByRole('article').filter({hasText:name});
 await expect(restored).toBeVisible();
 await restored.getByRole('button',{name:'Edit'}).click();
 await expect(editor.getByLabel('Description')).toHaveValue(description);
 expect(paid).toEqual([]);
});
