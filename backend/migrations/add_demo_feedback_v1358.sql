-- v135.8: Anonymous demo feedback, isolated from intelligence records.
-- Browser roles cannot select or insert directly. Only the authenticated
-- BAWASLU backend can accept anonymous submissions after validation/rate limits.
CREATE TABLE IF NOT EXISTS public.demo_feedback (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category VARCHAR(32) NOT NULL CHECK (category IN ('general','usability','data','bug','suggestion')),
 rating INTEGER NULL CHECK (rating BETWEEN 1 AND 5),
 message TEXT NOT NULL CHECK (char_length(message) BETWEEN 10 AND 1500),
 page_path VARCHAR(255) NOT NULL DEFAULT '/demo',
 language VARCHAR(5) NOT NULL DEFAULT 'id' CHECK (language IN ('id','en')),
 visitor_hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_demo_feedback_category ON public.demo_feedback(category);
CREATE INDEX IF NOT EXISTS ix_demo_feedback_visitor_hash ON public.demo_feedback(visitor_hash);
CREATE INDEX IF NOT EXISTS ix_demo_feedback_created_at ON public.demo_feedback(created_at);
ALTER TABLE public.demo_feedback ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.demo_feedback FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.demo_feedback_id_seq FROM anon, authenticated;
