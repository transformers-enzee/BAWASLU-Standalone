import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const page=read('../src/pages/IntelligenceAssistant.jsx');
const controls=read('../src/components/intel/AssistantWorkflowControls.jsx');
const evidence=read('../src/components/intel/AssistantWorkflowEvidence.jsx');
const server=read('../../backend/app/main.py');
const web=read('../../backend/app/assistant_orchestration.py');
const docker=read('../../Dockerfile');
assert.ok(page.includes("useState('WEB_ONLY')"));
assert.ok(page.includes('smartRadar:false,publicWeb:true,legalReferences:false,attachments:false'));
assert.ok(controls.includes('assistant-source-modes'));
assert.ok(page.includes("useState('EXECUTIVE')"));
assert.ok(page.includes('What are the latest verified BAWASLU and KPU updates'));
assert.ok(page.includes('sourceSelection.smartRadar?starters:webStarterPrompts'));
assert.ok(controls.includes('Public web / public social · recommended'));
assert.ok(server.includes("'response_profile':'WEB_RESEARCH'"));
assert.ok(server.includes('web_brief_text(research,language)'));
assert.ok(web.includes('if web_permitted and not explicit_private_source and not pdf_guidance else None'));
assert.ok(web.includes('Do not invent trend percentages'));
assert.ok(evidence.includes("webOnly=message?.response_profile==='WEB_RESEARCH'"));
const backendVersion=server.match(/BAWASLU_BUILD_VERSION','(\d+\.\d+)'/)?.[1];
const dockerVersion=docker.match(/ARG BAWASLU_BUILD_VERSION=(\d+\.\d+)/)?.[1];
assert.ok(backendVersion&&dockerVersion&&backendVersion===dockerVersion,'Backend and Docker release versions must match');
const [major,minor]=backendVersion.split('.').map(Number);
assert.ok(major>176||(major===176&&minor>=5),'Requires v176.5 or newer');
console.log('PASS multi-source research default, public source trace, concise BAWASLU actions and version parity');
