"""Real per-request PDF, editable Word, and structured Excel exports for AI-5.

No file is saved to a public static directory; authenticated API responses
stream the generated bytes. Export failure cannot modify the saved turn.
"""
import html
import io
import re
from datetime import datetime,timezone
from pathlib import Path

CITE=re.compile(r"\[\[([A-Z0-9:_-]{3,80})\]\]")
HEAD=re.compile(r"^(#{1,4})\s+(.+)$")
LIST=re.compile(r"^\s*[-*]\s+(.+)$")


def _plain(text):
    text=CITE.sub(lambda m:"["+m.group(1)+"]",str(text or ""))
    return re.sub(r"(?<!\\)[*_\x60]","",text)


def _outline(turn,edited_text=""):
    a=turn["answer"]
    body=edited_text or a.get("draft") or a.get("body") or ""
    return body[:21000],a.get("table") or {},a.get("open_questions") or []


def _sources(turn):
    answer=turn.get("answer") or {}
    used=set()
    table=answer.get("table") or {}
    for text in (answer.get("body",""),answer.get("draft",""),
                 table.get("title",""),*(table.get("columns") or [])):
        used.update(CITE.findall(str(text or "")))
    for row in (table.get("rows") or []):
        for cell in row if isinstance(row,list) else []:
            used.update(CITE.findall(str(cell or "")))
    for source in turn.get("sources",[]):
        if source.get("id") in used or str(source.get("type") or "").startswith("ATTACHMENT_"):
            yield source


def _source_label(source):
    title=str(source.get("title") or source.get("id") or "Source").strip()[:115]
    publication=str(source.get("published_at") or "")[:10]
    return title+(" ("+publication+")" if publication else "")


def _markup(text,sources):
    """Safe ReportLab inline markup; only application-verified URLs become links."""
    value=html.escape(str(text or ""))
    value=re.sub(r"\*\*([^*]{1,900})\*\*",r"<b>\1</b>",value)
    value=re.sub(r"(?<!\*)\*([^*]{1,900})\*",r"<i>\1</i>",value)
    def cite(match):
        source=sources.get(match.group(1))
        if not source:return "[citation unavailable]"
        label=html.escape(_source_label(source))
        url=str(source.get("resolved_url") or source.get("url") or "")
        if url.startswith("https://") and source.get("read_status") in ("READ","SAVED_SNAPSHOT"):
            return ('<link href="'+html.escape(url,quote=True)+'" color="#135F8B">'
                    +label+"</link>")
        return label
    return CITE.sub(cite,value)


def _font():
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    for path in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    ):
        if Path(path).is_file():
            try:
                if "AI5Unicode" not in pdfmetrics.getRegisteredFontNames():
                    pdfmetrics.registerFont(TTFont("AI5Unicode",path))
                return "AI5Unicode"
            except Exception:
                pass
    return "Helvetica"


def create_pdf(turn,edited=""):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate,Paragraph,Spacer,Table,TableStyle

    output=io.BytesIO()
    doc=SimpleDocTemplate(output,pagesize=A4,leftMargin=18*mm,rightMargin=18*mm,
                          topMargin=18*mm,bottomMargin=20*mm,
                          title=turn.get("answer",{}).get("title") or "AI-5 Research")
    font=_font()
    navy=colors.HexColor("#173950")
    styles={
       "body":ParagraphStyle("AI5Paragraph",fontName=font,fontSize=9.5,
                     leading=14.7,spaceAfter=8,wordWrap=None),
       "list":ParagraphStyle("AI5List",fontName=font,fontSize=9.5,
                     leading=14.5,spaceAfter=5,leftIndent=13,firstLineIndent=-10,
                     wordWrap=None),
       "h1":ParagraphStyle("AI5H1",fontName=font,fontSize=16.5,
                     leading=21,spaceBefore=16,spaceAfter=9,textColor=navy,
                     keepWithNext=True),
       "h2":ParagraphStyle("AI5H2",fontName=font,fontSize=13.2,
                     leading=18,spaceBefore=13,spaceAfter=7,textColor=navy,
                     keepWithNext=True),
       "h3":ParagraphStyle("AI5H3",fontName=font,fontSize=11.3,
                     leading=15.4,spaceBefore=10,spaceAfter=6,textColor=navy,
                     keepWithNext=True),
       "h4":ParagraphStyle("AI5H4",fontName=font,fontSize=10.1,
                     leading=14.6,spaceBefore=8,spaceAfter=5,textColor=navy,
                     keepWithNext=True),
       "small":ParagraphStyle("AI5Source",fontName=font,fontSize=8,
                     leading=11.8,spaceAfter=5,wordWrap=None,
                     textColor=colors.HexColor("#334155"))}
    eligible={row["id"]:row for row in turn.get("sources",[])
              if row.get("id") and row.get("read_status") in ("READ","SAVED_SNAPSHOT")
              and not row.get("duplicate_of")}
    story=[Paragraph(html.escape(turn.get("answer",{}).get("title") or "AI-5 Research"),
                     styles["h1"]),Spacer(1,4)]
    body,table,questions=_outline(turn,edited)
    paragraph=[]
    def flush():
        if paragraph:
            story.append(Paragraph(_markup(" ".join(paragraph),eligible),styles["body"]))
            paragraph.clear()
    for line in body.splitlines():
        line=line.strip()
        if not line:
            flush()
            continue
        heading=HEAD.match(line)
        unordered=LIST.match(line)
        numbered=re.match(r"^\d{1,3}[.)]\s+(.+)$",line)
        if heading:
            flush()
            level=min(4,len(heading.group(1)))
            story.append(Paragraph(_markup(heading.group(2),eligible),
                                   styles["h"+str(level)]))
        elif unordered or numbered:
            flush()
            story.append(Paragraph("&#8226; "+_markup(
                 unordered.group(1) if unordered else numbered.group(1),eligible),
                 styles["list"]))
        else:
            paragraph.append(line)
    flush()
    cols=table.get("columns") or []
    rows=table.get("rows") or []
    if cols:
        table_title_style=ParagraphStyle("AI5TableTitle",parent=styles["h2"],
                                           keepWithNext=False)
        story.append(Paragraph(html.escape(table.get("title") or "Structured comparison"),
                               table_title_style))
        # Wide comparisons stay readable as labeled country/subject sections.
        if len(cols)>4:
            for index,row in enumerate(rows[:100],1):
                title=str(row[0]) if row else "Item "+str(index)
                story.append(Paragraph(_markup(title,eligible),styles["h3"]))
                for j,label in enumerate(cols[1:],1):
                    value=str(row[j]) if j<len(row) else ""
                    story.append(Paragraph("<b>"+html.escape(str(label))+":</b> "+
                         _markup(value[:1400],eligible),styles["body"]))
        else:
            cells=[[Paragraph(_markup(str(name),eligible),styles["small"])
                    for name in cols]]
            for row in rows[:120]:
                cells.append([Paragraph(_markup(str(row[i])[:1800] if i<len(row) else "",
                                               eligible),styles["small"])
                              for i in range(len(cols))])
            usable=A4[0]-36*mm
            weights=([1.25]+[1]*(len(cols)-1)) if len(cols)>1 else [1]
            width=[usable*w/sum(weights) for w in weights]
            sheet=Table(cells,colWidths=width,repeatRows=1,hAlign="LEFT",
                        splitByRow=1)
            sheet.setStyle(TableStyle([
                ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#E7EEF3")),
                ("LINEBELOW",(0,0),(-1,0),.75,colors.HexColor("#B8C8D2")),
                ("LINEBELOW",(0,1),(-1,-1),.25,colors.HexColor("#E1E8EE")),
                ("VALIGN",(0,0),(-1,-1),"TOP"),
                ("LEFTPADDING",(0,0),(-1,-1),7),
                ("RIGHTPADDING",(0,0),(-1,-1),7),
                ("TOPPADDING",(0,0),(-1,-1),7),
                ("BOTTOMPADDING",(0,0),(-1,-1),7)
            ]))
            story.append(sheet)
    if questions:
        story.append(Paragraph("Open questions and evidence limits",styles["h2"]))
        for question in questions[:15]:
            story.append(Paragraph("&#8226; "+_markup(question,eligible),styles["list"]))
    story.append(Paragraph("Sources and provenance",styles["h2"]))
    selected=list(_sources(turn))
    if not selected:
        story.append(Paragraph("No verified sources were cited.",styles["small"]))
    for source in selected[:70]:
        title=html.escape(_source_label(source))
        date=html.escape(str(source.get("published_at") or "publication date unknown")[:30])
        status=html.escape(str(source.get("read_status") or "unknown"))
        url=str(source.get("resolved_url") or source.get("url") or "")
        label=("<link href='"+html.escape(url,quote=True)+"' color='#135F8B'>"+
                title+"</link>") if url.startswith("https://") else title
        story.append(Paragraph(label+" — "+status+" — "+date,styles["small"]))
    trace=turn.get("research_trace") or {}
    if trace.get("coverage"):
        story.append(Paragraph("Research Trail — coverage summary",styles["h2"]))
        for item in trace["coverage"][:12]:
            desc=str(item.get("name") or "")+" — "+str(item.get("status") or "")
            if item.get("reason"):desc+=": "+str(item["reason"])[:240]
            story.append(Paragraph(html.escape(desc),styles["small"]))
    story.append(Spacer(1,8))
    story.append(Paragraph("Prepared for human review. No official action was executed.",
                           styles["small"]))
    def footer(canvas,document):
        canvas.saveState()
        canvas.setFont(font,8)
        canvas.setFillColor(colors.HexColor("#66788A"))
        canvas.drawString(18*mm,12*mm,"AI-5 Research | For review")
        canvas.drawRightString(A4[0]-18*mm,12*mm,"Page "+str(document.page))
        canvas.restoreState()
    doc.build(story,onFirstPage=footer,onLaterPages=footer)
    return output.getvalue()


def _docx_cited(paragraph,text,source_index):
    """Insert approved clickable references into a real editable Word paragraph."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.opc.constants import RELATIONSHIP_TYPE as RT
    value=str(text or "")
    offset=0
    for match in CITE.finditer(value):
        if match.start()>offset:
            paragraph.add_run(re.sub(r"(?<!\\)[*_\x60]","",value[offset:match.start()]))
        source=source_index.get(match.group(1))
        if source:
            label=_source_label(source)
            url=str(source.get("resolved_url") or source.get("url") or "")
            if url.startswith("https://") and source.get("read_status") in ("READ","SAVED_SNAPSHOT"):
                rid=paragraph.part.relate_to(url,RT.HYPERLINK,is_external=True)
                link=OxmlElement("w:hyperlink")
                link.set(qn("r:id"),rid)
                run=OxmlElement("w:r")
                props=OxmlElement("w:rPr")
                color=OxmlElement("w:color");color.set(qn("w:val"),"135F8B")
                underline=OxmlElement("w:u");underline.set(qn("w:val"),"single")
                props.append(color);props.append(underline);run.append(props)
                value_xml=OxmlElement("w:t");value_xml.text=label
                run.append(value_xml);link.append(run);paragraph._p.append(link)
            else:paragraph.add_run(label)
        else:paragraph.add_run("[citation unavailable]")
        offset=match.end()
    if offset<len(value):
        paragraph.add_run(re.sub(r"(?<!\\)[*_\x60]","",value[offset:]))


def create_docx(turn,edited=""):
    from docx import Document
    from docx.shared import Inches
    doc=Document()
    section=doc.sections[0]
    section.top_margin=Inches(.8);section.bottom_margin=Inches(.8)
    section.left_margin=Inches(.85);section.right_margin=Inches(.85)
    index={s["id"]:s for s in turn.get("sources",[]) if s.get("id") and
           s.get("read_status") in ("READ","SAVED_SNAPSHOT") and
           not s.get("duplicate_of")}
    doc.add_heading(turn.get("answer",{}).get("title") or "AI-5 Research",0)
    body,table,questions=_outline(turn,edited)
    for line in body.splitlines():
        line=line.strip()
        if not line:continue
        heading=HEAD.match(line)
        bullet=LIST.match(line)
        numbered=re.match(r"^\d{1,3}[.)]\s+(.+)$",line)
        if heading:
            paragraph=doc.add_heading(level=min(4,len(heading.group(1))))
            _docx_cited(paragraph,heading.group(2),index)
        elif bullet or numbered:
            paragraph=doc.add_paragraph(style="List Bullet" if bullet else "List Number")
            _docx_cited(paragraph,bullet.group(1) if bullet else numbered.group(1),index)
        else:_docx_cited(doc.add_paragraph(),line,index)
    cols=table.get("columns") or []
    if cols:
        doc.add_heading(table.get("title") or "Structured comparison",level=2)
        grid=doc.add_table(rows=1,cols=len(cols))
        grid.style="Table Grid"
        for i,name in enumerate(cols):
            _docx_cited(grid.rows[0].cells[i].paragraphs[0],name,index)
        for row in (table.get("rows") or [])[:150]:
            cells=grid.add_row().cells
            for i in range(len(cols)):
                _docx_cited(cells[i].paragraphs[0],
                            str(row[i])[:1600] if i<len(row) else "",index)
    if questions:
        doc.add_heading("Open questions and evidence limits",level=2)
        for question in questions:
            _docx_cited(doc.add_paragraph(style="List Bullet"),question,index)
    doc.add_heading("Sources and provenance",level=2)
    for source in list(_sources(turn))[:60]:
        paragraph=doc.add_paragraph()
        _docx_cited(paragraph,"[["+str(source["id"])+"]]",index)
        paragraph.add_run(" — "+str(source.get("read_status") or "unknown"))
    if not list(_sources(turn)):doc.add_paragraph("No source citations attached.")
    doc.add_paragraph("Prepared for review. No external communication was sent.")
    result=io.BytesIO();doc.save(result)
    return result.getvalue()


def _literal(value):
    text=str(value or "")[:30000]
    # Prevent spreadsheet formula execution when user/model text starts with
    # common formula prefixes, including whitespace-prefixed formulas.
    return "'"+text if text.lstrip().startswith(("=","+","-","@")) else text


def create_xlsx(turn,edited=""):
    from openpyxl import Workbook
    from openpyxl.styles import PatternFill,Font,Alignment
    from openpyxl.utils import get_column_letter
    wb=Workbook()
    source_index={r["id"]:r for r in turn.get("sources",[]) if r.get("id")}
    def readable(value):
        return CITE.sub(lambda m:_source_label(source_index[m.group(1)])
                        if m.group(1) in source_index else "[citation unavailable]",
                        str(value or ""))
    main=wb.active;main.title="Analysis"
    body,table,questions=_outline(turn,edited)
    columns=table.get("columns") or []
    rows=table.get("rows") or []
    if columns:
        main.append([_literal(readable(x)) for x in columns])
        for row in rows[:250]:
            main.append([_literal(readable(row[i])) if i<len(row) else "" for i in range(len(columns))])
    else:
        main.append(["Section","Content","Status"])
        for line in body.splitlines():
            if line.strip():
                label="Heading" if HEAD.match(line) else "Finding / draft"
                main.append([label,_literal(_plain(readable(line))), "Requires review"])
        if main.max_row==1:main.append(["Finding","No generated content","No evidence"])
    main.freeze_panes="A2"
    main.auto_filter.ref=main.dimensions
    main.sheet_view.showGridLines=False
    for cell in main[1]:
        cell.font=Font(bold=True,color="FFFFFF")
        cell.fill=PatternFill("solid",fgColor="173950")
    for col in main.columns:
        letter=get_column_letter(col[0].column)
        main.column_dimensions[letter].width=min(65,max(17,max(len(str(c.value or "")) for c in col[:70])//2+5))
        for c in col:c.alignment=Alignment(vertical="top",wrap_text=True)
    sources=wb.create_sheet("Sources")
    sources.append(["Citation ID","Source title / file section","Type","Read status","Provenance",
                    "Publication date","Direct URL"])
    for s in list(_sources(turn))[:200]:
        sources.append([_literal(s.get(k)) for k in
                       ("id","title","type","read_status","basis","published_at","url")])
    sources.freeze_panes="A2";sources.auto_filter.ref=sources.dimensions
    for row in range(2,sources.max_row+1):
        url=str(sources.cell(row,7).value or "")
        if url.startswith("https://"):
            sources.cell(row,7).hyperlink=url
            sources.cell(row,7).style="Hyperlink"
            sources.cell(row,2).hyperlink=url
            sources.cell(row,2).style="Hyperlink"
    for cell in sources[1]:
        cell.font=Font(bold=True,color="FFFFFF")
        cell.fill=PatternFill("solid",fgColor="173950")
    for i,w in enumerate([25,58,25,20,34,20,62],1):
        sources.column_dimensions[get_column_letter(i)].width=w
    notes=wb.create_sheet("Context and caveats")
    notes.append(["Field","Value"])
    for k,v in [("Conversation mode",turn.get("mode")),("Source selection",turn.get("source_mode")),
                ("Original question",turn.get("question")),
                ("Generated at",datetime.now(timezone.utc).isoformat()),
                ("Editable draft",_plain(body[:18000])),
                ("Review policy","For review; no approval/sending/assignment was performed")]:
        notes.append([_literal(k),_literal(v)])
    for q in questions[:20]:notes.append(["Open question",_literal(q)])
    notes.column_dimensions["A"].width=27;notes.column_dimensions["B"].width=100
    for c in notes["B"]:c.alignment=Alignment(wrap_text=True,vertical="top")
    out=io.BytesIO();wb.save(out)
    return out.getvalue()


MIME={"pdf":"application/pdf",
      "docx":"application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "xlsx":"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"}


def create(turn,file_type,edited_text=""):
    if file_type not in MIME:raise ValueError("Unsupported export format")
    if not isinstance(edited_text,str) or len(edited_text)>22000:
        raise ValueError("Edited document text is too long")
    data=({"pdf":create_pdf,"docx":create_docx,"xlsx":create_xlsx}[file_type]
          (turn,edited_text))
    if not data or len(data)<100:raise ValueError("Empty or invalid generated file")
    return data,MIME[file_type],f"SmartRadar_AI5_{turn['turn_id'][:10]}.{file_type}"
