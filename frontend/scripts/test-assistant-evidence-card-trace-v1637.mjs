import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {evidenceCardId,mergeSocialCards,citationPresentation,canPrepareCaseworkFromCard} from '../src/lib/assistantEvidenceCards.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const a={record_type:'SOCIAL_LISTENING',record_id:'SOCIAL-1',source_post_id:1,campaign_id:2,source_excerpt:'Original'};
const b={record_type:'SOCIAL_LISTENING',record_id:'SOCIAL-2',source_post_id:2,campaign_id:2};
assert.deepEqual(mergeSocialCards([a,b],[{...a,source_excerpt:'Featured'}]).map(evidenceCardId),['SOCIAL-1','SOCIAL-2']);
assert.equal(mergeSocialCards([a,b],[a]).length,2);
assert.equal(citationPresentation(a,['SOCIAL-1']).kind,'CITED_IN_ANSWER');
assert.equal(citationPresentation(b,['SOCIAL-1']).kind,'CONTEXT_ONLY');
assert.equal(citationPresentation({record_id:'DOC-2-P1'},['DOC-2-P1']).cited,true);
assert.equal(citationPresentation({record_id:'DOC-2-P1'},[]).cited,false);
assert.equal(canPrepareCaseworkFromCard(a,false),false);
assert.equal(canPrepareCaseworkFromCard(a,true),true);
assert.equal(canPrepareCaseworkFromCard({...a,source_post_id:''},true),false);
assert.equal(canPrepareCaseworkFromCard({...a,campaign_id:''},true),false);
assert.equal(canPrepareCaseworkFromCard({...a,source_post_id:'1&case_id=5'},true),false);
const cards=read('src/components/intel/AssistantRecords.jsx'),page=read('src/pages/IntelligenceAssistant.jsx');
assert.ok(cards.includes('mergeSocialCards(records||[],featured||[])'));
assert.ok(cards.includes('data-evidence-citation-kind'));
assert.ok(cards.includes('canPrepareCaseworkFromCard(r,allowAssignments)'));
assert.ok(page.includes('citationIds={m.grounding?.grounding_audit?.displayed_citation_ids||[]}'));
assert.ok(page.includes("allowAssignments={reviewableIndexes.has(i)&&m.response_profile==='ACTION_REQUEST'}"));
const version=read('../backend/app/main.py').split("'build_version':'")[1]?.split("'")[0];
assert.ok(Number(version.replace('.',''))>=1637);
assert.ok(read('src/components/intel/Shell.jsx').includes('data-build-version="'+version+'"'));
console.log('PASS v163.7 cited-vs-context source labels, full inventory and fresh-only casework shortcuts');
