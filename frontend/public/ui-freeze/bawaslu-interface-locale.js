(function(){
  'use strict';
  const labels={...radarId,...customId};
  let locale='en';
  const originals=new WeakMap(),rendered=new WeakMap();
  const attrOriginals=new WeakMap(),attrRendered=new WeakMap();
  const attributes=['placeholder','title','aria-label','alt'];
  const ignoredTags=new Set(['SCRIPT','STYLE','NOSCRIPT','CODE','PRE','TEXTAREA','INPUT','SVG','PATH']);
  const excluded='[data-i18n-exempt],[data-original-content],.issue-source-description,.whitespace-pre-wrap,[data-post],[data-source-body],pre,code,textarea,[contenteditable]';
  function translate(value){
    if(locale!=='id'||typeof value!=='string')return value;
    const trimmed=value.trim();
    const direct=labels[trimmed];
    if(direct)return value.replace(trimmed,direct);
    const count=trimmed.match(/^([0-9][0-9.,]*) (posts|mentions|records|supporting posts)$/i);
    if(count){
      const words={posts:'unggahan',mentions:'penyebutan',records:'catatan','supporting posts':'unggahan pendukung'};
      return value.replace(trimmed,count[1]+' '+words[count[2].toLowerCase()]);
    }
    return value;
  }
  function skip(el){return !el||ignoredTags.has(el.tagName)||el.closest(excluded);}
  function scan(){
    if(!document.body)return;
    const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT);
    let node;
    while((node=walker.nextNode())){
      if(node.nodeType===3){
        if(skip(node.parentElement))continue;
        const current=node.nodeValue||'';
        if(!originals.has(node)||rendered.get(node)!==current)originals.set(node,current);
        const english=originals.get(node)||'';
        if(english.length>350)continue;
        const next=translate(english);
        if(current!==next)node.nodeValue=next;
        rendered.set(node,next);
      }else if(node.nodeType===1&&!skip(node)){
        let saved=attrOriginals.get(node),last=attrRendered.get(node);
        if(!saved){saved={};attrOriginals.set(node,saved);}
        if(!last){last={};attrRendered.set(node,last);}
        for(const name of attributes){
          if(!node.hasAttribute(name))continue;
          const current=node.getAttribute(name)||'';
          if(!(name in saved)||last[name]!==current)saved[name]=current;
          const next=translate(saved[name]);
          if(next!==current)node.setAttribute(name,next);
          last[name]=next;
        }
      }
    }
  }
  let scheduled=0;
  function schedule(){if(!scheduled)scheduled=requestAnimationFrame(()=>{scheduled=0;scan();});}
  function setLanguage(lang){
    locale=lang==='id'?'id':'en';
    document.documentElement.lang=locale;
    schedule();
  }
  window.addEventListener('message',event=>{
    if(event.origin!==window.location.origin||event.data?.type!=='BAWASLU_UI_LANGUAGE')return;
    setLanguage(event.data.language);
  });
  function start(){
    const requested=new URLSearchParams(window.location.search).get('lang');
    setLanguage(requested||window.localStorage.getItem('bawaslu-language')||'en');
    const observer=new MutationObserver(()=>schedule());
    observer.observe(document.body,{subtree:true,characterData:true,childList:true,
      attributes:true,attributeFilter:attributes});
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});
  else start();
  window.BAWASLUInterfaceLocale={setLanguage};
})();
