export function radarText(language,key){
  return language==='id'?(id[key]??key):key;
}
export function radarTitle(language,finding){
  if(!finding)return '';
  return language==='id'?(themes[finding.id]?.title??finding.title):finding.title;
}
export function radarInsight(language,finding,perspective){
  if(!finding)return '';
  // The curated Indonesian pilot insight is explicitly preliminary.
  // Do not dynamically machine-translate an existing AI summary or source.
  if(language==='id' && themes[finding.id]?.[perspective]){
    return themes[finding.id][perspective];
  }
  return finding.insights?.[perspective]||finding.summary||'';
}
export function radarTopic(language,value){
  return radarText(language,value);
}
